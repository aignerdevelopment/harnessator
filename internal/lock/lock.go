// Package lock reads and writes harnessator.lock: the committed record of
// what resolution actually pinned. Refs are ranges; the lock stores the
// exact tag and commit each source resolved to, plus a content digest per
// component so post-approval changes are detectable.
package lock

import (
	"fmt"
	"os"
	"sort"

	"github.com/BurntSushi/toml"

	"harnessator.org/harnessator/internal/schema"
)

// Header is written verbatim on every write; the body is machine generated.
const Header = "# harnessator.lock - generated by \"harnessator update\"; do not edit.\n"

// Lock is the whole file.
type Lock struct {
	Schema int `toml:"schema"`

	Sources []Source `toml:"source"`
	// Components is sorted by id on write for stable diffs.
	Components []Component `toml:"component"`
}

// Source pins one resolved source.
type Source struct {
	Name     string `toml:"name"`
	Git      string `toml:"git"`
	Range    string `toml:"range"`    // the ref expression from the config
	Resolved string `toml:"resolved"` // the tag (or branch head description)
	SHA      string `toml:"sha"`      // exact commit
	// Manifest is the repo-relative manifest path for multi-source repos
	// ("harnessator.toml" for plain single-source repos).
	Manifest string `toml:"manifest,omitempty"`
}

// Component pins one enabled component with its content digest.
type Component struct {
	ID     string `toml:"id"` // "<source>:<category>/<name>"
	Source string `toml:"source"`
	SHA    string `toml:"sha"`    // source commit this component came from
	Digest string `toml:"digest"` // "sha256:<hex>" content hash
}

// Read loads a lock file from disk.
func Read(path string) (*Lock, error) {
	var l Lock
	md, err := toml.DecodeFile(path, &l)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if und := md.Undecoded(); len(und) > 0 {
		return nil, fmt.Errorf("%s: unknown keys: %v", path, und)
	}
	if l.Schema != schema.SchemaVersion {
		return nil, fmt.Errorf("%s: unsupported lock schema %d (this build handles %d)",
			path, l.Schema, schema.SchemaVersion)
	}
	return &l, nil
}

// Write stores the lock deterministically: sources sorted by name,
// components sorted by id.
func (l *Lock) Write(path string) error {
	out := *l
	sort.Slice(out.Sources, func(a, b int) bool { return out.Sources[a].Name < out.Sources[b].Name })
	sort.Slice(out.Components, func(a, b int) bool { return out.Components[a].ID < out.Components[b].ID })
	out.Schema = schema.SchemaVersion

	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := f.WriteString(Header + "\n"); err != nil {
		return err
	}
	return toml.NewEncoder(f).Encode(&out)
}

// Source returns the pinned source by name.
func (l *Lock) Source(name string) (Source, bool) {
	for _, s := range l.Sources {
		if s.Name == name {
			return s, true
		}
	}
	return Source{}, false
}
