// KickstartFileName is the brief dropped next to the fossils. A prompt
// that scrolls past on stderr is a hint; a file an agent can be told to
// "work through" is a workflow.
const KickstartFileName = "HARNESSATOR-KICKSTART.md"

const kickstartTemplate = `# HARNESSATOR KICKSTART

This repository's agent instructions predate structure: one heroic
note file, several opinions, zero provenance. This brief turns the
fossil into governed rules. It is written to be executed by an AI
agent with good manners - and read by a human with less time.

Generated by 'harnessator kickstart' in @ROOT@.
The findings are live; rerun the command to refresh (--force).

## How to use this file (the human)

Hand it to whichever agent you trust most:

    Work through @FILE@. Report your plan before changing anything.

Then let it work and keep it honest with the gate at the bottom.
The agent drafts, the tool ratifies, you decide. The coffee policy
remains unenforced, as it should be.

## What the scan found

@FINDINGS@

Already publishable: @COUNT@ component(s). Everything beyond that
number is judgment work - which is why this file exists.

## The mission (the agent) - report first, then act

@MISSION@

Rules of engagement beyond the brief: quote, never paraphrase,
anything you move; when a section is two concerns wearing one hat,
split it and say so in your report.

## The gate (owned by the tool, non-negotiable)

` + "```" + `powershell
harnessator scan .
harnessator harvest . --name @SUGGESTED@ --dry-run
harnessator harvest . --name @SUGGESTED@
harnessator check --json
` + "```" + `

Refusals are findings, not suggestions. When the dry-run plans what
you intended: publish, delete this file, commit the source.

Two honest gotchas: publish WITHOUT --with-notes (once rules/ files
exist, that flag would heading-import the untouched fossil a second
time, duplicating the mission's work), and the final check --json
reports "project config not found" until this repo is adopted as a
consumer - the honest state of an unmanaged root, not damage.
`

// WriteKickstart scans the given roots and leaves a self-contained,
// paste-ready agent brief at the first root. Idempotent: it never
// touches an existing file unless force. Returns (path, wrote, error).
func WriteKickstart(paths []string, force bool) (string, bool, error) {
	if len(paths) == 0 {
		paths = []string{"."}
	}
	root, err := filepath.Abs(paths[0])
	if err != nil {
		return "", false, err
	}
	file := filepath.Join(root, KickstartFileName)
	if _, err := os.Stat(file); err == nil && !force {
		return file, false, nil
	}

	rep, err := Scan(paths)
	if err != nil {
		return "", false, err
	}
	var findings []string
	publishable := 0
	for _, r := range rep.Roots {
		publishable += len(r.Components)
		notes := map[string]bool{}
		for _, res := range r.Residual {
			if strings.Contains(res.Why, "agent note") {
				notes[res.Path] = true
			}
		}
		for _, note := range sortedKeys(notes) {
			abs := filepath.Join(r.Path, filepath.FromSlash(note))
			n := 1
			if rules, serr := SplitNoteFile(abs); serr == nil {
				n = len(rules)
			}
			pluralS := "s"
			if n == 1 {
				pluralS = ""
			}
			findings = append(findings, fmt.Sprintf(
				"- %s - unmanaged agent note; heading decoding would yield %d rule%s (layout is not intent - review)",
				note, n, pluralS))
		}
		for _, nm := range r.NearMiss {
			findings = append(findings, "- near-miss: "+nm)
		}
		for _, c := range r.Components {
			findings = append(findings, fmt.Sprintf("- publishable as-is: `%s/%s`", c.Category, c.ID))
		}
	}
	if len(findings) == 0 {
		findings = []string{"- (nothing note-shaped found - is this the right folder?)"}
	}

	mission := strings.ReplaceAll(GuidedTailPrompt,
		"Read ./AGENTS.md (or CLAUDE.md)", "Read the note files listed above")

	body := strings.NewReplacer(
		"@ROOT@", root,
		"@FILE@", KickstartFileName,
		"@FINDINGS@", strings.Join(findings, "\n"),
		"@COUNT@", fmt.Sprint(publishable),
		"@MISSION@", mission,
		"@SUGGESTED@", slugify(filepath.Base(root))+"-tools",
	).Replace(kickstartTemplate)

	if err := os.WriteFile(file, []byte(body), 0o644); err != nil {
		return "", false, err
	}
	return file, true, nil
}

func sortedKeys(m map[string]bool) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
