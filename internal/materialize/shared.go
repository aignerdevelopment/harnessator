// WriteShared renders the agent-facing index (.harnessator/active.md +
// active.json) and mirrors directory tools into .harnessator/tools/<id>/
// as link farms (edits in dev overlays propagate; local config/venvs stay
// possible) - the proven .agentictools/ pattern, harnessator-native.
func WriteShared(c *Context) error {
	base := filepath.Join(c.Project, ".harnessator")
	if err := os.MkdirAll(base, 0o755); err != nil {
		return err
	}
	resetLinkDir(c, filepath.Join(base, "tools"))

	// directory tool mirrors
	for _, ch := range c.byCategory("tool") {
		src, err := c.componentSrc(ch)
		if err != nil {
			return err
		}
		fi, err := os.Stat(src)
		if err != nil || !fi.IsDir() {
			continue
		}
		if c.DryRun {
			c.record("mirror tool dir %s -> .harnessator/tools/%s/", ch.ID, ch.ID)
			continue
		}
		dest := filepath.Join(base, "tools", ch.ID)
		if err := os.MkdirAll(dest, 0o755); err != nil {
			return err
		}
		resetLinkDir(c, dest) // purge stale entries from previous source versions
		entries, err := os.ReadDir(src)
		if err != nil {
			return err
		}
		for _, e := range entries {
			linkPath := filepath.Join(dest, e.Name())
			if err := c.link(filepath.Join(src, e.Name()), linkPath, e.IsDir()); err != nil {
				return err
			}
		}
	}

	// active.json
	type actCat struct {
		ID     string `json:"id"`
		Reason string `json:"reason"`
		Path   string `json:"path"`
	}
	sources := map[string]any{}
	components := map[string][]actCat{}
	for name, p := range c.Pins {
		sources[name] = map[string]any{
			"git": p.Git, "range": p.Range, "resolved": p.Resolved, "sha": p.SHA,
		}
	}
	for _, ch := range c.Plan.Enabled {
		path := filepath.ToSlash(ch.Component.Path)
		components[ch.Category] = append(components[ch.Category],
			actCat{ID: ch.Source + ":" + ch.ID, Reason: ch.Reason, Path: path})
	}
	active := map[string]any{"sources": sources, "components": components}
	raw, err := json.MarshalIndent(active, "", "  ")
	if err != nil {
		return err
	}
	if err := c.writeFile(filepath.Join(base, "active.json"), append(raw, '\n')); err != nil {
		return err
	}

	// active.md
	var md []byte
	md = append(md, []byte("# harnessator - active modules\n\nGenerated by `harnessator setup`. Do not edit. Load only these.\n\n")...)
	for _, name := range sortedPinNames(c.Pins) {
		p := c.Pins[name]
		md = append(md, []byte(fmt.Sprintf("- source `%s`: %s @ %s (%s)\n",
			name, p.Git, p.Resolved, short(p.SHA)))...)
	}
	for _, cat := range schema.Categories {
		choices := c.byCategory(cat)
		if len(choices) == 0 {
			continue
		}
		md = append(md, []byte("\n## "+cat+"\n\n")...)
		for _, ch := range choices {
			md = append(md, []byte(fmt.Sprintf("- **%s** — %s\n  - `%s`\n",
				ch.QualifiedID(), descOf(ch), filepath.Join(c.Pins[ch.Source].Dir,
					filepath.FromSlash(ch.Component.Path))))...)
		}
	}
	if len(c.Plan.Warnings) > 0 {
		md = append(md, []byte("\n## warnings\n\n")...)
		for _, w := range c.Plan.Warnings {
			md = append(md, []byte("- "+w+"\n")...)
		}
	}
	if err := c.writeFile(filepath.Join(base, "active.md"), md); err != nil {
		return err
	}
	return nil
}

func descOf(ch resolve.Choice) string {
	if ch.Component.Description != "" {
		return ch.Component.Description
	}
	return ch.Reason
}

func short(sha string) string {
	if len(sha) > 12 {
		return sha[:12]
	}
	return sha
}

// BuildLock turns pins and enabled components into a lock structure with
// content digests.
func BuildLock(c *Context) (*lock.Lock, error) {
	l := &lock.Lock{Schema: schema.SchemaVersion}
	for _, name := range sortedPinNames(c.Pins) {
		p := c.Pins[name]
		l.Sources = append(l.Sources, lock.Source{
			Name: p.Name, Git: p.Git, Range: p.Range, Resolved: p.Resolved,
			SHA: p.SHA, Manifest: manifestOrEmpty(p.ManifestFile()),
		})
	}
	for _, ch := range c.Plan.Enabled {
		src, err := c.componentSrc(ch)
		if err != nil {
			return nil, err
		}
		digest, err := contenthash.TreeOrFile(src)
		if err != nil {
			return nil, err
		}
		l.Components = append(l.Components, lock.Component{
			ID: ch.QualifiedID(), Source: ch.Source, SHA: c.Pins[ch.Source].SHA, Digest: digest,
		})
	}
	return l, nil
}

// manifestOrEmpty keeps the lock clean: the default root manifest needs no
// explicit field.
func manifestOrEmpty(m string) string {
	if m == "harnessator.toml" {
		return ""
	}
	return m
}
